// @ts-check
import { defineConfig } from 'astro/config';

import mdx from '@astrojs/mdx';
import AutoImport from 'astro-auto-import';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { satteri } from '@astrojs/markdown-satteri';
import { externalLinks } from './src/plugins/external-links.mjs';
import { imageNames } from './src/plugins/image-names.mjs';
import { layouts } from './src/plugins/layouts.mjs';

import tailwindcss from '@tailwindcss/vite';

// Components usable in any .mdx page without an import: every file in src/components except the ones the site uses internally.
const INTERNAL = ['Footer', 'Gallery', 'Header', 'ProjectCard', 'ProjectHead', 'ProjectSection', 'Tag'];
const components = readdirSync('./src/components')
  .filter((f) => f.endsWith('.astro'))
  .map((f) => f.replace('.astro', ''))
  .filter((name) => !INTERNAL.includes(name));

// Tell the editor about those components too (completion and props in .mdx). Rewritten only when the list changes.
const globals = `// Generated by astro.config.ts: components usable in .mdx without an import. Do not edit.
declare global {
${components.map((name) => `  const ${name}: typeof import('./components/${name}.astro').default;`).join('\n')}
}
export {};
`;
const globalsPath = './src/auto-imports.d.ts';
let current = '';
try { current = readFileSync(globalsPath, 'utf8'); } catch {}
if (current !== globals) writeFileSync(globalsPath, globals);

// https://astro.build/config
export default defineConfig({
  trailingSlash: 'ignore',

  // Adds a `crop` option to <Image> (see src/lib/crop-service.ts)
  image: { service: { entrypoint: fileURLToPath(new URL('./src/lib/crop-service.ts', import.meta.url)) } },

  integrations: [
    AutoImport({ imports: components.map((name) => ({ [`./src/components/${name}.astro`]: [['default', name]] })) }),
    mdx(),
  ],

  markdown: {
    shikiConfig: { theme: 'github-dark' },
    processor: satteri({ features: { directive: true }, mdastPlugins: [imageNames, layouts], hastPlugins: [externalLinks] }),
  },

  vite: {
    plugins: [tailwindcss()],
  },
});